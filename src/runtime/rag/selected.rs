//! Explicit source selection. The host quotes retrieved bodies; it never
//! presents those quotes as model-authored or repairs a malformed quotation.
use super::{invalid, Citation, CitedReport, SearchResult, VerifiedReport};
use crate::runtime::RuntimeError;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SourceSelectionReport {
    /// Uses `[[full_chunk_id]]` markers for entries in `sources`.
    pub text: String,
    /// Exact chunk IDs observed in this run. Full chunk-body quotations in
    /// canonical output are generated by the host, not copied by the model.
    pub sources: Vec<String>,
}
impl SearchResult {
    /// Resolve a distinct selection contract, with exact ID/body integrity.
    /// A missing/ambiguous/unretrieved source fails; no fuzzy ID repair exists.
    /// Selected full bodies establish provenance, never semantic claim support.
    pub fn verify_selection_all(
        results: &[Self],
        report: SourceSelectionReport,
    ) -> Result<VerifiedReport, RuntimeError> {
        Self::render_selection(results, report, false)
    }
    /// Explicit bibliography style: the host appends a labelled source list
    /// instead of requiring model-authored inline markers. Any markers the
    /// model DID supply must still name selected, actually retrieved sources.
    /// This is answer-level evidence, never per-claim entailment verification.
    pub fn render_selection_bibliography_all(
        results: &[Self],
        report: SourceSelectionReport,
    ) -> Result<VerifiedReport, RuntimeError> {
        Self::render_selection(results, report, true)
    }
    fn render_selection(
        results: &[Self],
        report: SourceSelectionReport,
        bibliography: bool,
    ) -> Result<VerifiedReport, RuntimeError> {
        if results.len() > 1024
            || report.sources.is_empty()
            || report.sources.len() > 20
            || report.text.trim().is_empty()
            || report.text.len() > 1024 * 1024
        {
            return Err(invalid(
                "source selection needs bounded evidence and 1..20 sources",
            ));
        }
        let mut citations = Vec::new();
        let mut total_bytes = 0usize;
        for id in &report.sources {
            if id.len() != 64
                || !id
                    .bytes()
                    .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
            {
                return Err(invalid(
                    "source selection requires exact lowercase chunk hashes",
                ));
            }
            let source = results
                .iter()
                .flat_map(|result| &result.hits)
                .find(|hit| &hit.chunk.id == id)
                .ok_or_else(|| invalid("selected source was not retrieved in this run"))?;
            total_bytes = total_bytes
                .checked_add(source.chunk.text.len())
                .ok_or_else(|| invalid("selected source bodies exceed output bound"))?;
            if total_bytes > 1024 * 1024 {
                return Err(invalid("selected source bodies exceed 1MiB output bound"));
            }
            citations.push(Citation {
                chunk_id: id.clone(),
                quote: source.chunk.text.clone(),
            });
        }
        // The ordinary verifier checks conflicting evidence, chunk hashes,
        // duplicate IDs, every marker, quote size and exact archived bodies.
        let text = if bibliography {
            format!("{}\n\n[Source list rendered by the host from model-selected evidence; semantic support not verified.]\n{}",
                report.text,report.sources.iter().map(|id|format!("[[{id}]]")).collect::<Vec<_>>().join(" "))
        } else {
            report.text
        };
        Self::verify_all(results, CitedReport { text, citations })
    }
}
